def full_images(source, label):
    class Images(HTMLParser):
        def __init__(self):
            super().__init__(convert_charrefs=False)
            self.stack = []
            self.edits = []
            self.lines = source.splitlines(keepends=True)

        def handle_starttag(self, tag, attrs):
            attrs = dict(attrs)
            if tag == 'img':
                src = attrs.get('src', '')
                classes = attrs.get('class', '') + ' ' + ' '.join(c for _, c in self.stack)
                if not any(t == 'a' for t, _ in self.stack) and not re.search(r'(screen-stack|screen-dark|screen-light|preview-dark|preview-light|popup-preview|app-frame)', classes) and re.search(r'(screenshot|guide-(ru|de|en)|interface|demo-|app-(ru|de|en)|main-window|Ui-|control-|recordings-|surface-laptop|filters-|manual/)', src, re.I):
                    line, col = self.getpos()
                    start = sum(map(len, self.lines[:line - 1])) + col
                    tagtext = self.get_starttag_text()
                    replacement = '<a class="guide-full-image" href="' + html.escape(src, quote=True) + '" aria-label="' + label + '">' + tagtext + '</a>'
                    self.edits.append((start, start + len(tagtext), replacement))
            if tag not in ('img', 'input', 'br', 'hr', 'meta', 'link', 'source', 'wbr', 'area', 'base', 'embed', 'param'):
                self.stack.append((tag, attrs.get('class', '')))

        def handle_endtag(self, tag):
            for i in range(len(self.stack) - 1, -1, -1):
                if self.stack[i][0] == tag:
                    self.stack = self.stack[:i]
                    break
    p = Images()
    p.feed(source)
    for a, b, text in reversed(p.edits):
        source = source[:a] + text + source[b:]
    return source


def block(s, name, text):
    """Replace <!-- name:start -->...<!-- name:end --> (the markers stay)."""
    pattern = '<!-- %s:start -->.*?<!-- %s:end -->' % (name, name)
    if not re.search(pattern, s, re.S):
        raise ValueError('missing marker ' + name)
    return re.sub(pattern, lambda _: '<!-- %s:start -->%s<!-- %s:end -->' % (name, text, name), s, count=1, flags=re.S)


def main():
    cfg, d = bp.load()
    site = ROOT / cfg['folder']
    version = bp.kit_version()
    (site / 'guide-polish.css').write_bytes(CSS.encode('utf-8'))
    guide_css = '<link rel="stylesheet" href="guide-polish.css?v=%s">' % bp.file_hash(CSS)
    pages = {l: 'Guide-%s.html' % l for l in bp.LANGS}
    for path in sorted(site.glob('Guide-*.html')):
        lang = path.stem[-2:]
        if lang not in COPY:
            continue
        s = path.read_bytes().decode('utf-8').replace('\r\n', '\n')
        s = block(s, 'ppk-head', '\n' + bp.head_block(cfg, d, version, guide_css) + '\n')
        s = block(s, 'ppk-header', '\n<a class="ppk-skip" href="#main">%s</a>\n%s\n' % (bp.TEXT[lang]['skip'], bp.header_block(cfg, d, lang, pages)))
        s = block(s, 'ppk-footer', '\n' + bp.footer_block(d, lang) + '\n')
        # Release summary: no self links, plain headings.
        start, end = s.find('<!-- public-release:start -->'), s.find('<!-- public-release:end -->')
        if start >= 0 and end > start:
            part = s[start:end]
            part = re.sub(r'<a\b[^>]*href="[^"]*Guide-' + lang + r'\.html"[^>]*>.*?</a>', '', part, flags=re.S)
            part = re.sub(r'(<h2) id="section-\d+"', r'\1', part)
            s = s[:start] + part + s[end:]
        s = re.sub(r'<!-- guide-polish:start -->.*?<!-- guide-polish:end -->\s*', '', s, flags=re.S)
        headings = []
        release_start, release_end = s.find('<!-- public-release:start -->'), s.find('<!-- public-release:end -->')

        main_start, main_end = s.index('<main'), s.index('</main>')

        def heading(m):
            if not main_start < m.start() < main_end or (release_start >= 0 and release_start < m.start() < release_end):
                return m[0]
            attrs, title = m.group(1), m.group(2)
            label = html.unescape(re.sub('<[^>]+>', '', title)).strip()
            if not label:
                return m[0]
            existing = re.search(r'\bid="([^"]+)"', attrs)
            key = existing[1] if existing else 'section-' + str(len(headings) + 1)
            if not existing:
                attrs += ' id="' + key + '"'
            headings.append((key, label))
            return '<h2' + attrs + '>' + title + '</h2>'
        s = re.sub(r'<h2\b([^>]*)>(.*?)</h2>', heading, s, flags=re.S)
        t = COPY[lang]
        has_contents = bool(re.search(r'class="[^"]*(?:toc|guide-nav|contents)[^"]*"', s))
        tools = ''
        if len(headings) > 3 and not has_contents:
            tools = ('<!-- guide-polish:start --><aside class="guide-tools"><details><summary>' + t[0] + '</summary><ol>' +
                     ''.join('<li><a href="#' + html.escape(k) + '">' + html.escape(v) + '</a></li>' for k, v in headings) +
                     '</ol></details></aside><!-- guide-polish:end -->\n')
        anchor = '<!-- public-release:end -->' if '<!-- public-release:end -->' in s else '<!-- guide-hero:end -->'
        s = s.replace(anchor, anchor + '\n' + tools.rstrip('\n'), 1) if tools else s
        s = full_images(s, t[1])
        path.write_bytes(s.encode('utf-8'))


if __name__ == '__main__':
    main()
